// 改写缓存以前只有「正文|模式」。提示词变了就要换前缀，避免命中旧的故事稿。
export const REWRITE_PROMPT_VERSION = "20261031-4";
export const STORY_TEMPERATURE = 0.85;

export function rewriteKeyMaterial(text, mode, variant = "") {
  const version = variant
    ? `prompt-${REWRITE_PROMPT_VERSION}|${variant}`
    : `prompt-${REWRITE_PROMPT_VERSION}`;
  return `${version}|${String(text || "")}|${mode || "announcer"}`;
}

export function storyLengthTarget(length) {
  const n = Math.max(0, Number(length) || 0);
  const min = Math.max(n, Math.round(n * 3));
  const max = Math.max(min, Math.round(n * 5));
  return { min, max };
}

